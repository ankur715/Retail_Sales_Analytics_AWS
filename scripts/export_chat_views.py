"""Export the chatbot's chat.* views from Redshift into a Postgres seed for the
local Docker Compose stack (docker-compose.yml, profile `app`).

Runs from the laptop (Redshift only accepts its IP), as the chatbot's read-only
chat_reader user, so it can read nothing but the chat views. A few thousand rows:
seconds of Redshift compute. Writes:

  docker/postgres/initdb/10_chat_views.sql   tables named like the views + COPY + grants
  docker/postgres/initdb/data/<view>.csv     the rows

The copy is a snapshot: weeks_ago is frozen at export time. Re-run after new loads:
  .venv/bin/python -m scripts.export_chat_views
"""
import csv
from pathlib import Path

from chatbot import catalog, db

OUT = Path(__file__).resolve().parent.parent / "docker" / "postgres" / "initdb"
PG_TYPES = {"character varying": "TEXT", "timestamp without time zone": "TIMESTAMP"}


def main() -> None:
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    cols = db.query("SELECT table_name, column_name, data_type FROM information_schema.columns "
                    "WHERE table_schema = 'chat' ORDER BY table_name, ordinal_position")["rows"]
    ddl = ["-- Generated by scripts/export_chat_views.py from Redshift chat.* views. Do not edit.",
           "CREATE SCHEMA IF NOT EXISTS chat;"]
    for view in catalog.view_names():
        name = view.split(".", 1)[1]
        columns = [(c, PG_TYPES.get(t, t.upper())) for table, c, t in cols if table == name]
        result = db.query(f"SELECT {', '.join(c for c, _ in columns)} FROM {view} ORDER BY 1")
        with open(OUT / "data" / f"{name}.csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(result["columns"])
            w.writerows(result["rows"])
        ddl.append(f"CREATE TABLE {view} (\n  " + ",\n  ".join(f"{c} {t}" for c, t in columns) + "\n);")
        ddl.append(f"COPY {view} FROM '/docker-entrypoint-initdb.d/data/{name}.csv' WITH (FORMAT csv, HEADER true);")
        print(f"{view}: {result['row_count']} rows")
    ddl += ["GRANT USAGE ON SCHEMA chat TO chat_reader;",
            "GRANT SELECT ON ALL TABLES IN SCHEMA chat TO chat_reader;"]
    (OUT / "10_chat_views.sql").write_text("\n".join(ddl) + "\n")


if __name__ == "__main__":
    main()
